const dictionaries = { en, am, om };
const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(
    () => storage.getItem('paraware.lang') || 'en'
  );

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dataset.lang = lang;
    storage.setItem('paraware.lang', lang);
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang: (next) => {
        if (dictionaries[next]) setLangState(next);
      },
      t: (key, vars) => {
        let text = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
        if (vars) {
          for (const [name, val] of Object.entries(vars)) {
            text = text.replaceAll(`{${name}}`, String(val));
          }
        }
        return text;
      },
    }),
    [lang]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}

export function languageLabel(id) {
  return LANGUAGES.find((language) => language.id === id)?.label || 'English';
}
